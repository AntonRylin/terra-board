import { useEffect, useState } from 'react';
import { Copy, Check } from 'lucide-react';
import { Group, Row, Switch } from './settings/controls';
import type { McpStatus } from '../bridge';
// The configuration holds this computer's paths, so the prompt is only valid
// when copied from the Terra Board installation it should connect to.
const claudePrompt = (
  config: string,
) => `Connect Terra Board to Claude on this computer. Terra Board is a local whiteboard app; its MCP server is named terra_board and uses this stdio configuration, generated by the app for this computer:

${config}

Use the command, args and env exactly as given. Do not change the paths, do not add a URL or token, and do not install Node or any proxy: the connector is bundled with the app.

1. Claude Desktop: find claude_desktop_config.json. On Windows it is normally %APPDATA%\\Claude\\claude_desktop_config.json; Microsoft Store installs keep it under %LOCALAPPDATA%\\Packages\\Claude_*\\LocalCache\\Roaming\\Claude. On macOS it is ~/Library/Application Support/Claude/claude_desktop_config.json. On Linux it is ~/.config/Claude/claude_desktop_config.json. Make a backup copy next to it, then add terra_board to the existing mcpServers object. Keep every other server and setting unchanged and keep the file valid JSON.
2. Claude Code, if the claude command is installed: register the same entry for all projects with claude mcp add-json --scope user terra_board '<the terra_board object as one JSON string>', then confirm with claude mcp get terra_board.
3. Check that the command and the mcp-stdio.cjs file exist at the given paths. If they do not, stop and tell me instead of guessing other paths.

When done, tell me to fully quit and reopen Claude, and that Terra Board must stay open with Settings → AI access via MCP switched on. After the restart, call list_boards to confirm the connection.`;
export default function McpSettings() {
  const [status, setStatus] = useState<McpStatus | null>(null),
    [port, setPort] = useState('47831'),
    [busy, setBusy] = useState(false),
    [error, setError] = useState(''),
    [copied, setCopied] = useState('');
  useEffect(() => {
    window.canvas
      ?.mcpStatus()
      .then((s) => {
        setStatus(s);
        setPort(String(s.port));
      })
      .catch((e) => setError(String(e)));
  }, []);
  const update = async (enabled: boolean) => {
    setBusy(true);
    setError('');
    try {
      const p = Number(port);
      if (!Number.isInteger(p) || p < 1024 || p > 65535)
        throw Error('Choose a port between 1024 and 65535.');
      setStatus(await window.canvas!.mcpUpdate({ enabled, port: p }));
    } catch (e) {
      setError(String(e));
    } finally {
      setBusy(false);
    }
  };
  useEffect(() => {
    if (!copied) return;
    const timer = setTimeout(() => setCopied(''), 2500);
    return () => clearTimeout(timer);
  }, [copied]);
  const copy = async (name: string, value: string) => {
    setError('');
    try {
      await (window.canvas ? window.canvas.copyText(value) : navigator.clipboard.writeText(value));
      setCopied(name);
    } catch {
      setError('Could not copy the setup.');
    }
  };
  const clients = status && [
    {
      name: 'Codex',
      hint: 'Paste into config.toml, then restart Codex.',
      value: status.codexConfig,
    },
    {
      name: 'Claude',
      hint: 'Paste into Claude Code, then restart Claude.',
      value: claudePrompt(status.claudeConfig),
    },
  ];
  return (
    <div className="mcp-settings">
      <Group>
        <Row
          id="mcpAccess"
          below={
            <div className="mcp-state">
              <span className={'mcp-dot ' + (status?.running ? 'running' : '')} />
              {status?.running
                ? 'On. Keep Terra Board open.'
                : status?.enabled
                  ? 'Could not start'
                  : window.canvas
                    ? 'Off'
                    : 'Available in the desktop app.'}
            </div>
          }
        >
          <Switch
            label="Enable MCP server"
            checked={!!status?.enabled}
            disabled={busy || !status}
            onChange={(enabled) => update(enabled)}
          />
        </Row>
        <Row id="mcpPort">
          <span className="mcp-port">
            <input
              aria-label="MCP port"
              type="number"
              min="1024"
              max="65535"
              value={port}
              onChange={(e) => setPort(e.target.value)}
            />
            <button
              type="button"
              className="st-button"
              disabled={busy || !status || Number(port) === status.port}
              onClick={() => update(!!status?.enabled)}
            >
              Apply
            </button>
          </span>
        </Row>
      </Group>
      {(error || status?.error) && (
        <p className="st-notice error mcp-error" role="alert">
          {error || status?.error}
        </p>
      )}
      {clients && (
        <Group title="Connect an app">
          {clients.map((client) => (
            <Row key={client.name} title={client.name} description={client.hint}>
              <button
                type="button"
                className="st-button"
                aria-label={`Copy ${client.name} setup`}
                onClick={() => copy(client.name, client.value)}
              >
                <Copy size={15} />
                Copy setup
              </button>
            </Row>
          ))}
        </Group>
      )}
      {copied && (
        <div className="toast" role="status">
          <Check size={15} />
          {copied} setup prompt copied
        </div>
      )}
    </div>
  );
}
